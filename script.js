const readStorageValue = (key) => {
  try {
    return window.localStorage.getItem(key);
  } catch (error) {
    return null;
  }
};

const writeStorageValue = (key, value) => {
  try {
    window.localStorage.setItem(key, value);
  } catch (error) {
    // storage unavailable, ignore
  }
};

const resolveTranslation = (lang, key) => {
  const safeLang = TRADUCTIONS[lang] ? lang : 'fr';
  const root = TRADUCTIONS[safeLang];
  const parts = key.split('.');
  let value = root;

  for (const part of parts) {
    if (!value || !Object.prototype.hasOwnProperty.call(value, part)) {
      if (safeLang !== 'fr') {
        return resolveTranslation('fr', key);
      }
      return '';
    }
    value = value[part];
  }

  if (typeof value === 'string') {
    return value;
  }

  if (safeLang !== 'fr') {
    return resolveTranslation('fr', key);
  }

  return '';
};

const getPreferredLanguage = () => {
  const saved = readStorageValue('portfolioLang');
  if (saved && TRADUCTIONS[saved]) {
    return saved;
  }

  const browserLang = navigator.language || navigator.userLanguage || 'fr';
  const normalized = browserLang.toLowerCase();

  if (normalized.startsWith('ar')) return 'ar';
  if (normalized.startsWith('fr')) return 'fr';

  return 'fr';
};

const isArabicLocale = (lang) => lang === 'ar';

const updateTextNodes = (lang) => {
  const safeLang = TRADUCTIONS[lang] ? lang : 'fr';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    const text = resolveTranslation(safeLang, key);
    if (typeof text === 'string') {
      element.textContent = text;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    const value = resolveTranslation(safeLang, key);
    if (typeof value === 'string') {
      element.setAttribute('placeholder', value);
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const key = element.dataset.i18nAria;
    const value = resolveTranslation(safeLang, key);
    if (typeof value === 'string') {
      element.setAttribute('aria-label', value);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    const key = element.dataset.i18nTitle;
    const value = resolveTranslation(safeLang, key);
    if (typeof value === 'string') {
      element.setAttribute('title', value);
    }
  });
};

const syncHeroCopy = (lang) => {
  const heroTheme = document.body.dataset.heroTheme || 'restaurant';
  const safeLang = TRADUCTIONS[lang] ? lang : 'fr';
  const themeCopy = TRADUCTIONS[safeLang].hero.subtitle[heroTheme] || TRADUCTIONS[safeLang].hero.subtitle.restaurant;

  if (heroSubtitle) {
    heroSubtitle.textContent = themeCopy;
  }

  if (heroParagraph) {
    heroParagraph.textContent = resolveTranslation(safeLang, 'hero.paragraph');
  }

  if (heroJobText) {
    const value = TRADUCTIONS[safeLang].hero.readout.job[heroTheme] || 'RESTAURANT';
    heroJobText.textContent = value;
  }

  if (heroFormText) {
    heroFormText.textContent = `${String((document.body.dataset.heroIndex || 0) + 1).padStart(2, '0')}/04`;
  }
};

const setLang = (lang) => {
  const selectedLang = TRADUCTIONS[lang] ? lang : 'fr';
  const root = document.documentElement;
  root.lang = selectedLang;
  root.dir = isArabicLocale(selectedLang) ? 'rtl' : 'ltr';
  document.body.setAttribute('data-lang', selectedLang);
  document.body.classList.toggle('rtl', isArabicLocale(selectedLang));

  const pageTitle = document.querySelector('title');
  const metaDescription = document.querySelector('meta[name="description"]');

  if (pageTitle) {
    pageTitle.textContent = resolveTranslation(selectedLang, 'meta.title');
  }

  if (metaDescription) {
    metaDescription.setAttribute('content', resolveTranslation(selectedLang, 'meta.description'));
  }

  updateTextNodes(selectedLang);

  document.querySelectorAll('.lang-btn[data-lang]').forEach((button) => {
    const active = button.dataset.lang === selectedLang;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  writeStorageValue('portfolioLang', selectedLang);
  syncHeroCopy(selectedLang);
};

const initLocaleSystem = () => {
  try {
    const langButtons = document.querySelectorAll('.lang-btn[data-lang]');
    langButtons.forEach((button) => {
      button.addEventListener('click', () => {
        const lang = button.dataset.lang || 'fr';
        setLang(lang);
      });
    });

    setLang(getPreferredLanguage());
  } catch (error) {
    console.warn('Locale system failed:', error);
    document.documentElement.lang = 'fr';
    document.documentElement.dir = 'ltr';
  }
};

