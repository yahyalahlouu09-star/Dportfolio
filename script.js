const whatsAppLinks = document.querySelectorAll('[data-whatsapp-key]');

function updateWhatsAppLinks(lang) {
  const map = translations[lang] || translations.ar;

  whatsAppLinks.forEach((link) => {
    const key = link.dataset.whatsappKey;
    const messageKey = whatsappKeys[key];
    const text = map[messageKey] || map.whatsappGeneral || 'Hello Yahya';
    link.href = `https://wa.me/${WHATSAPP_PHONE}?text=${encodeURIComponent(text)}`;
  });
}

const filterButtons = document.querySelectorAll('.filter-btn');
const cards = document.querySelectorAll('.project-card');

filterButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const filter = button.dataset.filter;

    filterButtons.forEach((btn) => btn.classList.toggle('active', btn === button));

    cards.forEach((card) => {
      const shouldShow = filter === 'all' || card.dataset.category === filter;
      card.classList.toggle('is-hidden', !shouldShow);
    });
  });
});

const revealEls = document.querySelectorAll('.reveal');
const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
      }
    });
  },
  { threshold: 0.12 }
);

revealEls.forEach((el) => observer.observe(el));

const langButtons = document.querySelectorAll('.lang-btn');
const translatable = document.querySelectorAll('[data-i18n]');
const brandText = document.querySelector('.brand-name');

function applyLanguage(lang) {
  const map = translations[lang] || translations.ar;
  document.body.dataset.lang = lang;
  document.body.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  translatable.forEach((element) => {
    const key = element.dataset.i18n;
    if (map[key]) {
      element.textContent = map[key];
    }
  });

  const screenLabel = document.querySelector('.screen-label');
  const screenTitle = document.querySelector('.screen-hero h3');
  if (screenLabel && map.screenLabel) screenLabel.textContent = map.screenLabel;
  if (screenTitle && map.screenTitle) screenTitle.textContent = map.screenTitle;

  if (brandText && map.brandName) {
    brandText.textContent = map.brandName;
  }

  const brandMark = document.querySelector('[data-brand-mark]');
  if (brandMark) {
    brandMark.textContent = lang === 'ar' ? 'ي' : 'Y';
  }

  updateWhatsAppLinks(lang);

  langButtons.forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

document.getElementById('year').textContent = new Date().getFullYear();
applyLanguage('fr');
