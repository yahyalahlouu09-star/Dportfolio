const faqItems = document.querySelectorAll('.faq-item');
const yearEl = document.getElementById('year');
const dot = document.querySelector('.cursor-dot');
const ring = document.querySelector('.cursor-ring');

function buildWhatsAppLink(message) {
  const text = encodeURIComponent(message || `Bonjour ${CONFIG.nom}, je voudrais un site pour mon activité.`);
  return `https://wa.me/${CONFIG.whatsapp}?text=${text}`;
}

function setLocalTime() {
  const timeEl = document.getElementById('local-time');
  if (!timeEl) return;

  const now = new Date();
  const formatted = new Intl.DateTimeFormat('fr-FR', {
    timeZone: 'Africa/Casablanca',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false
  }).format(now);

  timeEl.textContent = formatted;
}

function updateWhatsAppLinks() {
  document.querySelectorAll('[data-whatsapp-message]').forEach((link) => {
    const message = link.getAttribute('data-whatsapp-message');
    link.href = buildWhatsAppLink(message);
  });

  document.querySelectorAll('a[href^="https://wa.me/"]').forEach((link) => {
    const current = link.href;
    if (current.includes('wa.me')) {
      const url = new URL(current);
      const text = url.searchParams.get('text') || `Bonjour ${CONFIG.nom}, je voudrais un site pour mon activité.`;
      url.searchParams.set('text', text);
      link.href = url.toString();
    }
  });
}

function initMenu() {
  if (!menuToggle || !mobileMenu) return;

  menuToggle.addEventListener('click', () => {
    const isOpen = mobileMenu.classList.toggle('is-open');
    mobileMenu.setAttribute('aria-hidden', String(!isOpen));
    menuToggle.setAttribute('aria-expanded', String(isOpen));
  });

  mobileMenu.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => {
      mobileMenu.classList.remove('is-open');
      menuToggle.setAttribute('aria-expanded', 'false');
      mobileMenu.setAttribute('aria-hidden', 'true');
    });
  });
}

function initFaq() {
  faqItems.forEach((item) => {
    const button = item.querySelector('.faq-question');
    if (!button) return;

    button.addEventListener('click', () => {
      const isOpen = item.classList.contains('open');
      faqItems.forEach((faq) => faq.classList.remove('open'));
      faqItems.forEach((faq) => faq.querySelector('.faq-question')?.setAttribute('aria-expanded', 'false'));
      if (!isOpen) {
        item.classList.add('open');
        button.setAttribute('aria-expanded', 'true');
      }
    });
  });
}

function initProjects() {
  const setProjectState = (index) => {
    projectSlides.forEach((slide, i) => slide.classList.toggle('active', i === index));
    projectRailItems.forEach((item, i) => item.classList.toggle('active', i === index));
  };

  projectRailItems.forEach((item, index) => {
    item.addEventListener('click', () => setProjectState(index));
  });

  projectSlides.forEach((slide, index) => {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            setProjectState(index);
          }
        });
      },
      { threshold: 0.6 }
    );

    observer.observe(slide);
  });
}

function initServices() {
  serviceItems.forEach((item) => {
    item.addEventListener('mouseenter', () => {
      const image = item.dataset.image;
      if (image && servicePreview) {
        servicePreview.style.backgroundImage = `linear-gradient(135deg, rgba(7,7,10,0.12), rgba(7,7,10,0.42)), url('${image}')`;
      }
      serviceItems.forEach((el) => el.classList.toggle('active', el === item));
    });
  });
}

function initCursor() {
  if (window.matchMedia('(pointer: coarse)').matches) return;

  window.addEventListener('pointermove', (event) => {
    if (dot) {
      dot.style.left = `${event.clientX}px`;
      dot.style.top = `${event.clientY}px`;
    }
    if (ring) {
      ring.style.left = `${event.clientX}px`;
      ring.style.top = `${event.clientY}px`;
    }
  });

  document.querySelectorAll('a, button, input, textarea').forEach((el) => {
    el.addEventListener('pointerenter', () => {
      if (ring) {
        ring.style.width = '56px';
        ring.style.height = '56px';
        ring.style.borderColor = 'rgba(124, 92, 255, 0.8)';
        ring.style.background = 'rgba(124, 92, 255, 0.08)';
      }
    });

    el.addEventListener('pointerleave', () => {
      if (ring) {
        ring.style.width = '40px';
        ring.style.height = '40px';
        ring.style.borderColor = 'rgba(237, 235, 255, 0.45)';
        ring.style.background = 'rgba(237, 235, 255, 0.04)';
      }
    });
  });
}

function initHeroReveal() {
  const targets = [heroLineTop, heroLineBottom].filter(Boolean);
  if (!targets.length) return;

  const reveal = () => {
    if (window.gsap) {
      gsap.from(targets, {
        opacity: 0,
        y: 28,
        duration: 0.9,
        ease: 'power3.out',
        stagger: 0.12
      });

      gsap.from(heroWords, {
        opacity: 0,
        y: 26,
        duration: 0.9,
        delay: 0.18,
        ease: 'power3.out',
        stagger: 0.08
      });
    }
  };

  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(reveal);
  } else {
    reveal();
  }
}

function initHeroTextCycle() {
  if (!heroSelectorDots.length) return;

  const themeOrder = ['restaurant', 'clinique', 'sport', 'salon'];
  let activeIndex = 0;
  let cycleTimer = null;

  const setTheme = (index) => {
    activeIndex = index;
    const selectedTheme = themeOrder[activeIndex] || 'restaurant';
    document.body.dataset.heroTheme = selectedTheme;
    document.body.dataset.heroIndex = String(activeIndex);
    heroVisual?.setAttribute('data-theme', selectedTheme);

    heroSelectorDots.forEach((dot) => {
      const isActive = dot.dataset.theme === selectedTheme;
      dot.classList.toggle('is-active', isActive);
    });

    const lang = document.documentElement.lang || 'fr';
    const labels = TRADUCTIONS[lang]?.hero?.subtitle || TRADUCTIONS.fr.hero.subtitle;
    const heroCopy = labels[selectedTheme] || labels.restaurant;

    if (heroSubtitle) {
      heroSubtitle.textContent = heroCopy;
    }

    if (heroJobText) {
      heroJobText.textContent = TRADUCTIONS[lang]?.hero?.readout?.job?.[selectedTheme] || 'RESTAURANT';
    }

    if (heroFormText) {
      heroFormText.textContent = `${String(activeIndex + 1).padStart(2, '0')}/04`;
    }

    if (window.__heroOrbThemeSync) {
      window.__heroOrbThemeSync(selectedTheme);
    }

    if (heroSubtitle) {
      heroSubtitle.style.opacity = '0';
      heroSubtitle.style.transform = 'translateY(8px)';
      setTimeout(() => {
        const currentLang = document.documentElement.lang || 'fr';
        const currentLabels = TRADUCTIONS[currentLang]?.hero?.subtitle || TRADUCTIONS.fr.hero.subtitle;
        heroSubtitle.textContent = currentLabels[selectedTheme] || currentLabels.restaurant;
        heroSubtitle.style.opacity = '1';
        heroSubtitle.style.transform = 'translateY(0)';
      }, 400);
    }
  };

  const startCycle = () => {
    window.clearInterval(cycleTimer);
    cycleTimer = window.setInterval(() => {
      setTheme((activeIndex + 1) % themeOrder.length);
    }, 3000);
  };

  heroSelectorDots.forEach((dot) => {
    dot.addEventListener('pointerenter', () => window.clearInterval(cycleTimer));
    dot.addEventListener('pointerleave', startCycle);
    dot.addEventListener('click', () => {
      const nextIndex = themeOrder.indexOf(dot.dataset.theme || 'restaurant');
      if (nextIndex >= 0) {
        setTheme(nextIndex);
        startCycle();
      }
    });
  });

  setTheme(0);
  if (!prefersReducedMotion) startCycle();
}

function initHero3D() {
  if (prefersReducedMotion) return;

  const canvas = document.getElementById('hero-canvas');
  if (!canvas || !window.THREE) return;

  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(35, 1, 0.1, 1000);
  camera.position.z = 5.4;

  const renderer = new THREE.WebGLRenderer({
    canvas,
    alpha: true,
    antialias: true,
    powerPreference: 'high-performance'
  });
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
  renderer.setClearColor(0x000000, 0);

  const group = new THREE.Group();
  scene.add(group);

  const uniforms = {
    uTime: { value: 0 },
    uColorA: { value: new THREE.Color('#ffb069') },
    uColorB: { value: new THREE.Color('#7c5cff') },
    uColorC: { value: new THREE.Color('#39d8df') }
  };

  const orbMaterial = new THREE.ShaderMaterial({
    uniforms,
    transparent: true,
    side: THREE.DoubleSide,
    vertexShader: `
      uniform float uTime;
      varying vec3 vNormal;
      varying vec3 vWorldPosition;
      varying vec3 vPosition;

      float noise(vec3 p) {
        return sin(p.x * 3.0 + uTime * 1.3) * sin(p.y * 4.1 - uTime * 1.1) * sin(p.z * 2.7 + uTime * 0.9);
      }

      void main() {
        vec3 transformed = position;
        float displacement = noise(position + uTime * 0.2);
        transformed += normal * displacement * 0.28;

        vec4 worldPosition = modelMatrix * vec4(transformed, 1.0);
        vWorldPosition = worldPosition.xyz;
        vPosition = transformed;
        vNormal = normalize(normalMatrix * normal);

        gl_Position = projectionMatrix * viewMatrix * worldPosition;
      }
    `,
    fragmentShader: `
      uniform vec3 uColorA;
      uniform vec3 uColorB;
      uniform vec3 uColorC;
      varying vec3 vNormal;
      varying vec3 vWorldPosition;
      varying vec3 vPosition;

      void main() {
        vec3 normal = normalize(vNormal);
        vec3 viewDir = normalize(cameraPosition - vWorldPosition);
        float fresnel = pow(1.0 - max(dot(normal, viewDir), 0.0), 2.6);

        float mixA = smoothstep(-0.8, 1.0, vPosition.y * 0.7 + 0.5);
        vec3 base = mix(uColorA, uColorB, mixA);
        vec3 accent = mix(base, uColorC, 0.5 + fresnel * 0.7);
        vec3 color = accent + fresnel * 0.22;
        color = min(color, vec3(0.82));

        gl_FragColor = vec4(color, 1.0);
      }
    `
  });

  const mesh = new THREE.Mesh(new THREE.IcosahedronGeometry(1.55, 2), orbMaterial);
  group.add(mesh);

  const halo = new THREE.Mesh(
    new THREE.TorusGeometry(1.9, 0.04, 24, 180),
    new THREE.MeshBasicMaterial({
      color: 0x8fe6ff,
      transparent: true,
      opacity: 0.6
    })
  );
  halo.rotation.x = Math.PI / 2.2;
  halo.rotation.y = 0.8;
  group.add(halo);

  const particleCount = window.innerWidth > 768 ? 1100 : 520;
  const particlePositions = new Float32Array(particleCount * 3);
  for (let i = 0; i < particleCount * 3; i += 3) {
    const radius = 2.4 + Math.random() * 1.8;
    const theta = Math.random() * Math.PI * 2;
    const phi = Math.acos(2 * Math.random() - 1);
    particlePositions[i] = radius * Math.sin(phi) * Math.cos(theta);
    particlePositions[i + 1] = radius * Math.cos(phi);
    particlePositions[i + 2] = radius * Math.sin(phi) * Math.sin(theta);
  }

  const particleGeometry = new THREE.BufferGeometry();
  particleGeometry.setAttribute('position', new THREE.BufferAttribute(particlePositions, 3));

  const particles = new THREE.Points(
    particleGeometry,
    new THREE.PointsMaterial({
      color: 0xc7d7ff,
      size: window.innerWidth > 768 ? 0.022 : 0.028,
      transparent: true,
      opacity: 0.72,
      depthWrite: false
    })
  );
  group.add(particles);

  scene.add(new THREE.AmbientLight(0xffffff, 1.2));

  const keyLight = new THREE.DirectionalLight(0x7c5cff, 2.2);
  keyLight.position.set(3.5, 3.2, 4.5);
  scene.add(keyLight);

  const fillLight = new THREE.PointLight(0x2de2e6, 2.1, 18, 2);
  fillLight.position.set(-3, -1.8, 3);
  scene.add(fillLight);

  const syncTheme = (theme) => {
    const paletteMap = {
      restaurant: ['#ffb069', '#7c5cff', '#39d8df'],
      clinique: ['#8fe0ff', '#4ed6d8', '#39d8df'],
      sport: ['#ff9c62', '#ff5a3d', '#ffc96b'],
      salon: ['#f5bfd3', '#d48cff', '#7c5cff']
    };

    const [a, b, c] = paletteMap[theme] || paletteMap.restaurant;
    uniforms.uColorA.value.set(a);
    uniforms.uColorB.value.set(b);
    uniforms.uColorC.value.set(c);
    halo.material.color.set(c);
  };

  window.__heroOrbThemeSync = syncTheme;
  syncTheme(heroVisual?.dataset.theme || 'restaurant');

  const resize = () => {
    const width = canvas.clientWidth || canvas.parentElement.clientWidth || 520;
    const height = canvas.clientHeight || canvas.parentElement.clientHeight || 520;
    renderer.setSize(width, height, false);
    camera.aspect = width / height;
    camera.updateProjectionMatrix();
  };

  resize();
  window.addEventListener('resize', resize);

  let pointerX = 0;
  let pointerY = 0;
  window.addEventListener('pointermove', (event) => {
    pointerX = (event.clientX / window.innerWidth) * 2 - 1;
    pointerY = -(event.clientY / window.innerHeight) * 2 + 1;
  });

  let isVisible = true;
  const handleVisibility = () => {
    isVisible = !document.hidden;
  };
  document.addEventListener('visibilitychange', handleVisibility);

  function animate() {
    if (!isVisible) {
      requestAnimationFrame(animate);
      return;
    }

    const t = performance.now() * 0.001;
    uniforms.uTime.value = t;

    mesh.rotation.x += 0.004;
    mesh.rotation.y += 0.006;
    group.rotation.y -= 0.0028;
    group.rotation.x = pointerY * 0.38;
    group.rotation.z = pointerX * 0.46;
    halo.rotation.z += 0.005;
    particles.rotation.y -= 0.0009;
    particles.rotation.x += 0.0005;

    renderer.render(scene, camera);
    requestAnimationFrame(animate);
  }

  requestAnimationFrame(animate);
}

function initPreloader() {
  if (!preloader || !preloaderFill || !preloaderNumber) return;

  const value = { current: 0 };
  const timeline = gsap.timeline({ defaults: { ease: 'power3.out' } });

  timeline.to(value, {
    current: 100,
    duration: 1.4,
    onUpdate: () => {
      const numeric = Math.round(value.current);
      preloaderFill.style.width = `${numeric}%`;
      preloaderNumber.textContent = numeric;
    }
  });

  timeline.to(preloader, {
    duration: 0.8,
    autoAlpha: 0,
    onComplete: () => preloader.remove()
  }, '+=0.1');

  gsap.to(heroLines, {
    yPercent: 0,
    opacity: 1,
    duration: 1.1,
    delay: 0.6,
    stagger: 0.12,
    ease: 'power3.out'
  });
}

function initManifesto() {
  if (!manifestoWords.length) return;

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          manifestoWords.forEach((item, index) => {
            item.style.transitionDelay = `${index * 0.08}s`;
            item.classList.add('is-visible');
          });
        }
      });
    },
    { threshold: 0.35 }
  );

  observer.observe(document.querySelector('.manifesto-section'));
}

function initScrollProgress() {
  if (!progressBar) return;

  const update = () => {
    const scrollTop = window.scrollY;
    const total = document.body.scrollHeight - window.innerHeight;
    const ratio = total > 0 ? scrollTop / total : 0;
    progressBar.style.transform = `scaleX(${ratio})`;
  };

  window.addEventListener('scroll', update, { passive: true });
  update();
}

function initContactForm() {
  const form = document.querySelector('.contact-form');
  if (!form) return;

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    const name = document.getElementById('client-name')?.value?.trim() || 'Client';
    const activity = document.getElementById('client-activity')?.value?.trim() || 'activité';
    const message = document.getElementById('client-message')?.value?.trim() || 'Je souhaite un site pour mon activité.';
    window.open(buildWhatsAppLink(`Bonjour ${CONFIG.nom}, je suis ${name}, je veux un site pour ${activity}. ${message}`), '_blank');
  });
}

function initYear() {
  if (yearEl) {
    yearEl.textContent = new Date().getFullYear();
  }
}

function initGsap() {
  if (!window.gsap || !window.ScrollTrigger) return;

  gsap.registerPlugin(ScrollTrigger);

  document.querySelectorAll('.project-slide').forEach((slide, index) => {
    ScrollTrigger.create({
      trigger: slide,
      start: 'top 50%',
      end: 'bottom 50%',
      onEnter: () => {
        projectSlides.forEach((item, i) => item.classList.toggle('active', i === index));
        projectRailItems.forEach((item, i) => item.classList.toggle('active', i === index));
      },
      onEnterBack: () => {
        projectSlides.forEach((item, i) => item.classList.toggle('active', i === index));
        projectRailItems.forEach((item, i) => item.classList.toggle('active', i === index));
      }
    });
  });

  gsap.to(progressBar, {
    scaleX: 1,
    ease: 'none',
    scrollTrigger: {
      trigger: document.body,
      start: 'top top',
      end: 'bottom bottom',
      scrub: true
    }
  });

  document.querySelectorAll('.process-step').forEach((step) => {
    gsap.from(step, {
      opacity: 0,
      y: 30,
      duration: 0.8,
      ease: 'power3.out',
      scrollTrigger: {
        trigger: step,
        start: 'top 80%'
      }
    });
  });

  const processGrid = document.querySelector('.process-grid');
  if (processGrid) {
    ScrollTrigger.create({
      trigger: processGrid,
      start: 'top 75%',
      onEnter: () => processGrid.classList.add('is-visible')
    });
  }
}

function initLenis() {
  if (!window.Lenis) return;

  const lenis = new Lenis({
    duration: 1.05,
    smoothWheel: true,
    smoothTouch: false
  });

  function raf(time) {
    lenis.raf(time);
    requestAnimationFrame(raf);
  }

  requestAnimationFrame(raf);
}

function init() {
  updateWhatsAppLinks();
  setLocalTime();
  setInterval(setLocalTime, 60000);
  initMenu();
  initFaq();
  initProjects();
  initServices();
  initCursor();
  initYear();
  initContactForm();
  initScrollProgress();
  initManifesto();

  if (!prefersReducedMotion) {
    initPreloader();
    initHeroReveal();
    initHeroTextCycle();
    initHero3D();
    initGsap();
    initLenis();
  } else {
    if (preloader) preloader.remove();
    const canvas = document.getElementById('hero-canvas');
    if (canvas) {
      canvas.style.background = 'radial-gradient(circle at center, rgba(124, 92, 255, 0.2), rgba(0, 0, 0, 0.2), transparent 70%)';
      canvas.style.borderRadius = '50%';
    }
    initHeroTextCycle();
  }
}

